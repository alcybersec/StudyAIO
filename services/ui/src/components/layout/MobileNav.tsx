export function MobileNav() {
  const location = useLocation()
  const { data: dashboard } = useDashboard()
  const [moreOpen, setMoreOpen] = useState(false)
  const pendingCount = dashboard?.pending_review_count ?? 0

  const isActive = (path: string) => {
    if (path === '/') return location.pathname === '/'
    return location.pathname.startsWith(path)
  }

  // "More" is active if any of its sub-items is active
  const moreActive = moreItems.some((item) => isActive(item.path))

  return (
    <>
      <nav className="lg:hidden fixed bottom-0 inset-x-0 bg-surface border-t border-border z-50 safe-area-pb">
        <div className="flex items-center justify-around h-14">
          {tabs.map((tab) => (
            <Link
              key={tab.path}
              to={tab.path}
              className={`relative flex flex-col items-center justify-center gap-0.5 w-full h-full text-xs transition-colors min-h-[44px] ${
                isActive(tab.path) ? 'text-primary font-medium' : 'text-text-muted'
              }`}
            >
              {tab.icon}
              <span>{tab.label}</span>
            </Link>
          ))}

          {/* More button */}
          <button
            onClick={() => setMoreOpen(true)}
            className={`relative flex flex-col items-center justify-center gap-0.5 w-full h-full text-xs transition-colors min-h-[44px] ${
              moreActive ? 'text-primary font-medium' : 'text-text-muted'
            }`}
          >
            {MoreIcon}
            <span>More</span>
            {pendingCount > 0 && (
              <span className="absolute top-1 right-1/4 bg-primary text-white text-[10px] font-bold rounded-full w-4 h-4 flex items-center justify-center">
                {pendingCount > 9 ? '9+' : pendingCount}
              </span>
            )}
          </button>
        </div>
      </nav>

      {/* More Sheet */}
      <Sheet open={moreOpen} onOpenChange={setMoreOpen} side="bottom" title="More">
        <div className="space-y-1 pb-4">
          {moreItems.map((item) => (
            <Link
              key={item.path}
              to={item.path}
              onClick={() => setMoreOpen(false)}
              className={`flex items-center gap-3 px-3 py-3 rounded-lg text-sm font-medium transition-colors min-h-[44px] ${
                isActive(item.path)
                  ? 'bg-primary/10 text-primary'
                  : 'text-text hover:bg-surface-alt'
              }`}
            >
              {item.icon}
              <span>{item.label}</span>
              {item.path === '/review' && pendingCount > 0 && (
                <span className="ml-auto bg-primary text-white text-xs font-bold rounded-full px-1.5 py-0.5 min-w-[1.25rem] text-center">
                  {pendingCount}
                </span>
              )}
            </Link>
          ))}
        </div>
      </Sheet>
    </>
  )
}
